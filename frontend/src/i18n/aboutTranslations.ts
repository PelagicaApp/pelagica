let initialized = false;

export function registerAboutTranslations(): void {
    if (initialized) return;
    initialized = true;

    for (const [lang, translations] of Object.entries(aboutTranslations)) {
        // Add to 'about' namespace
        i18n.addResourceBundle(lang, 'about', translations, true, true);

        // Also add 'about' key to 'sidebar' namespace so TopBar profile menu translates it automatically
        i18n.addResourceBundle(lang, 'sidebar', { about: translations.about }, true, false);
    }
}

// Auto-register immediately upon module import
registerAboutTranslations();
